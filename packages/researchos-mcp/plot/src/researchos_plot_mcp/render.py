import json
import os
import subprocess
import sys
from pathlib import Path


def render_chart_py(spec: dict) -> str:
    payload = json.dumps(spec, ensure_ascii=False)
    return f'''# Generated by ResearchOS. This file is self-contained and safe to version.
import json
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

SPEC = json.loads({payload!r})
THEMES = {{
    "nature": {{"font.family": "sans-serif", "font.size": 7, "axes.linewidth": 0.5, "axes.spines.top": False, "axes.spines.right": False}},
    "science": {{"font.family": "sans-serif", "font.size": 7, "axes.linewidth": 0.6, "axes.grid": False}},
    "ieee": {{"font.family": "serif", "font.size": 8, "axes.linewidth": 0.6}},
    "prism": {{"font.family": "sans-serif", "font.size": 8, "axes.linewidth": 0.75, "axes.spines.top": False, "axes.spines.right": False}},
}}
PALETTES = {{
    "nature": ["#E64B35", "#4DBBD5", "#00A087", "#3C5488", "#F39B7F"],
    "science": ["#0C4B8E", "#BF382A", "#F2AD00", "#7F8C8D", "#27AE60"],
    "ieee": ["#111111", "#555555", "#888888", "#BBBBBB", "#DDDDDD"],
    "prism": ["#1F77B4", "#FF7F0E", "#2CA02C", "#D62728", "#9467BD"],
}}

def render_grouped_bar(df, ax, enc, palette):
    error = {{"sd": "sd", "sem": "se", "ci95": ("ci", 95)}}.get(enc.get("error"))
    sns.barplot(data=df, x=enc["x"], y=enc["y"], hue=enc.get("group"), errorbar=error, palette=palette, ax=ax)

def render_scatter_regression(df, ax, enc, palette):
    group = enc.get("group")
    if group:
        sns.scatterplot(data=df, x=enc["x"], y=enc["y"], hue=group, palette=palette, ax=ax)
        for _name, frame in df.groupby(group):
            sns.regplot(data=frame, x=enc["x"], y=enc["y"], scatter=False, ci=95, ax=ax)
        return
    sns.regplot(data=df, x=enc["x"], y=enc["y"], ci=95, color=palette[0], ax=ax)

def render_boxplot(df, ax, enc, palette):
    sns.boxplot(data=df, x=enc["x"], y=enc["y"], hue=enc.get("group"), palette=palette, ax=ax)

def render_violin(df, ax, enc, palette):
    sns.violinplot(data=df, x=enc["x"], y=enc["y"], hue=enc.get("group"), palette=palette, inner="box", ax=ax)
    sns.stripplot(data=df, x=enc["x"], y=enc["y"], hue=enc.get("group"), color="black", alpha=0.45, size=2, legend=False, ax=ax)

def render_survival(df, ax, enc, palette):
    groups = [(None, df)] if not enc.get("group") else list(df.groupby(enc["group"]))
    for index, (name, frame) in enumerate(groups):
        ordered = frame.sort_values(enc["x"])
        at_risk = len(ordered)
        survival = 1.0
        xs, ys = [0.0], [1.0]
        for _, row in ordered.iterrows():
            time = float(row[enc["x"]])
            if bool(row[enc["y"]]):
                survival *= (at_risk - 1) / at_risk
            xs.extend([time, time])
            ys.extend([ys[-1], survival])
            at_risk -= 1
        ax.step(xs, ys, where="post", label=None if name is None else str(name), color=palette[index % len(palette)])
    ax.set_ylim(0, 1.03)

def render_heatmap(df, ax, _enc, _palette):
    sns.heatmap(df.select_dtypes(include="number").corr(), cmap="vlag", center=0, annot=True, fmt=".2f", ax=ax)

def add_annotations(df, ax, spec):
    enc = spec["encoding"]
    category = enc.get("group") or enc.get("x")
    if not category or category not in df.columns or not spec.get("annotations"):
        return
    labels = [str(value) for value in pd.unique(df[category])]
    y_values = pd.to_numeric(df[enc["y"]], errors="coerce")
    y_min, y_max = float(y_values.min()), float(y_values.max())
    span = max(y_max - y_min, abs(y_max) * 0.1, 1.0)
    for index, annotation in enumerate(spec["annotations"]):
        left, right = [labels.index(str(value)) for value in annotation["groups"]]
        y = y_max + span * (0.08 + index * 0.1)
        ax.plot([left, left, right, right], [y, y + span * 0.025, y + span * 0.025, y], color="black", linewidth=0.6)
        ax.text((left + right) / 2, y + span * 0.035, annotation["stars"], ha="center", va="bottom")
    ax.set_ylim(top=y_max + span * (0.2 + len(spec["annotations"]) * 0.1))

def main():
    df = pd.read_csv(Path(__file__).with_name("data.csv"))
    enc = SPEC["encoding"]
    with matplotlib.rc_context(THEMES[SPEC["theme"]]):
        figure, ax = plt.subplots(figsize=(3.5, 2.7))
        globals()[f"render_{{SPEC['template']}}"](df, ax, enc, PALETTES[SPEC["theme"]])
        axes = SPEC.get("axes", {{}})
        ax.set_xlabel(axes.get("x_label", enc.get("x", "")))
        ax.set_ylabel(axes.get("y_label", enc.get("y", "")))
        ax.tick_params(labelsize=axes.get("tick_font_size", 7))
        if axes.get("y_lim"):
            ax.set_ylim(*axes["y_lim"])
        if not SPEC.get("legend", {{}}).get("show", True) and ax.get_legend():
            ax.get_legend().remove()
        elif ax.get_legend():
            ax.legend(loc=SPEC.get("legend", {{}}).get("position", "best"))
        add_annotations(df, ax, SPEC)
        figure.tight_layout()
        output = Path(__file__).with_name("out")
        output.mkdir(exist_ok=True)
        figure.savefig(output / "figure.svg", bbox_inches="tight")
        figure.savefig(output / "figure.pdf", bbox_inches="tight")
        plt.close(figure)

if __name__ == "__main__":
    main()
'''


def execute_chart(code_path: Path, timeout_seconds: int = 120) -> None:
    environment = {**os.environ, "MPLBACKEND": "Agg", "PYTHONNOUSERSITE": "1"}
    result = subprocess.run(
        [sys.executable, str(code_path)],
        cwd=code_path.parent,
        env=environment,
        capture_output=True,
        text=True,
        check=False,
        timeout=timeout_seconds,
    )
    if result.returncode:
        raise RuntimeError((result.stderr or result.stdout)[-4000:])
